#!/usr/bin/env python3
"""Generate result-state bindings from the governed public contract."""

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
CONTRACT = ROOT / "contracts" / "result-states-v6.json"


def go_identifier(value):
    return "".join(part.capitalize() for part in value.split("_"))


def quoted(values):
    return ", ".join(json.dumps(value) for value in values)


def render(document):
    states = list(document["evidence_result_states"])
    actual = document["actual_verdicts"]
    scores = document["scores"]
    validate_go = """// Code generated by scripts/generate_result_state_bindings.py; DO NOT EDIT.\n\npackage main\n\nvar validActualVerdicts = map[string]bool{%s}\n\nvar validScores = map[string]bool{%s}\n\nvar validResultStates = map[string]bool{%s}\n""" % (
        ", ".join(f"{json.dumps(value)}: true" for value in actual),
        ", ".join(f"{json.dumps(value)}: true" for value in scores),
        ", ".join(f"{json.dumps(value)}: true" for value in states),
    )
    runner_go = "// Code generated by scripts/generate_result_state_bindings.py; DO NOT EDIT.\n\npackage main\n\nconst (\n" + "".join(
        f"\tResultState{go_identifier(value)} ResultState = {json.dumps(value)}\n"
        for value in states
    ) + ")\n"
    python = """# Code generated by scripts/generate_result_state_bindings.py; DO NOT EDIT.\n\nRESULT_SCHEMA_VERSION = %d\nSCORING_VERSION = %s\nACTUAL_VERDICTS = frozenset((%s,))\nSCORES = frozenset((%s,))\nRESULT_STATES = frozenset((%s,))\n""" % (
        document["result_schema_version"],
        json.dumps(document["scoring_version"]),
        quoted(actual),
        quoted(scores),
        quoted(states),
    )
    return {
        ROOT / "validate" / "result_states_generated.go": validate_go,
        ROOT / "runner" / "result_states_generated.go": runner_go,
        ROOT / "scripts" / "result_states_generated.py": python,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    document = json.loads(CONTRACT.read_text(encoding="utf-8"))
    outputs = render(document)
    stale = []
    for path, expected in outputs.items():
        if args.write:
            path.write_text(expected, encoding="utf-8")
        elif not path.is_file() or path.read_text(encoding="utf-8") != expected:
            stale.append(path.relative_to(ROOT).as_posix())
    if stale:
        raise SystemExit("stale result-state bindings: " + ", ".join(stale))
    print(f"result-state bindings: OK ({len(outputs)} generated files)")


if __name__ == "__main__":
    main()
